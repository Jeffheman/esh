# Emits the code-memory tables used by the shell on SDCC targets. SDCC has no
# section attributes, so ADD_CMD/AUTO_CMD descriptors are found by symbol name
# in the compiled objects instead.
#
# Usage: gen_shell_cmd_table.sh <object.rel>...

set -euo pipefail

if [ "$#" -eq 0 ]; then
  echo "usage: $0 <object.rel>..." >&2
  exit 2
fi

SDNM=${SDNM:-sdnm}

if ! command -v "$SDNM" >/dev/null 2>&1; then
  echo "error: $SDNM not found; set SDNM to the SDCC symbol dumper" >&2
  exit 1
fi

mapfile -t symbols < <(
  "$SDNM" "$@" | awk 'NF >= 3 && $2 != "U" { print $3 }' | sort -u
)

# SDCC prefixes every C identifier with an underscore, so the C name
# _shell_cmd_hello appears in the object as __shell_cmd_hello.
cmd_symbols=()
auto_symbols=()
for symbol in "${symbols[@]}"; do
  case "$symbol" in
    __shell_cmd_*) cmd_symbols+=("${symbol#_}") ;;
    __shell_auto_*) auto_symbols+=("${symbol#_}") ;;
  esac
done

if [ "${#cmd_symbols[@]}" -eq 0 ]; then
  echo "error: no _shell_cmd_* symbols found in: $*" >&2
  exit 1
fi

if [ "${#auto_symbols[@]}" -eq 0 ]; then
  echo "error: no _shell_auto_* symbols found in: $*" >&2
  exit 1
fi

echo "/* Generated by tools/gen_shell_cmd_table.sh. Do not edit. */"
echo "#include \"shell.h\""
echo
for symbol in "${cmd_symbols[@]}" "${auto_symbols[@]}"; do
  echo "extern SHELL_CODE cmd_t $symbol;"
done
echo
echo "SHELL_CODE cmd_t *const shell_cmd_table[] = {"
for symbol in "${cmd_symbols[@]}"; do
  echo "  &$symbol,"
done
echo "  0"
echo "};"
echo
echo "SHELL_CODE cmd_t *const shell_auto_table[] = {"
for symbol in "${auto_symbols[@]}"; do
  echo "  &$symbol,"
done
echo "  0"
echo "};"
